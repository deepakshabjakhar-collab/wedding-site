const BY_ID = new Map(TEMPLATES.map((t) => [t.id, t]));
export function getTemplate(id) {
    return BY_ID.get(id) ?? TEMPLATES[0];
}
export function resolveTheme(templateId, overrides) {
    const template = getTemplate(templateId);
    const fontPair = FONT_PAIRS.find((f) => f.id === overrides?.fontPair);
    const script = SCRIPT_FONTS.find((f) => f.id === overrides?.scriptFont);
    return {
        template,
        palette: { ...template.palette, ...(overrides?.palette ?? {}) },
        display: fontPair?.stack ?? template.display,
        body: template.body,
        script: script?.stack ?? template.script,
        layout: template.layout,
    };
}
export function themeStyle(theme) {
    return {
        '--inv-bg': theme.palette.bg,
        '--inv-surface': theme.palette.surface,
        '--inv-ink': theme.palette.ink,
        '--inv-muted': theme.palette.muted,
        '--inv-accent': theme.palette.accent,
        '--inv-accent-soft': theme.palette.accentSoft,
        '--inv-line': theme.palette.line,
        '--inv-deep': theme.palette.deep,
        '--inv-deep-ink': theme.palette.deepInk,
        '--inv-display': theme.display,
        '--inv-body': theme.body,
        '--inv-script': theme.script,
    };
}
