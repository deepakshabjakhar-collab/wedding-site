import fs from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const OUT_DIR = path.join(ROOT, 'public', 'fonts');
const CSS_OUT = path.join(ROOT, 'src', 'styles', 'fonts.css');

/**
 * Nothing ordinary. Every family here is either a high-contrast Didone, a deco
 * display serif, an ornamental engraved face or a copperplate/Spencerian script.
 */
const FAMILIES = [
  ['Italiana', 'wght@400'],
  ['Gilda Display', 'wght@400'],
  ['Bodoni Moda', 'ital,wght@0,400;0,500;0,600;1,400'],
  ['Playfair Display', 'ital,wght@0,400;0,500;0,600;0,700;1,400;1,500'],
  ['Cormorant Garamond', 'ital,wght@0,300;0,400;0,500;0,600;0,700;1,300;1,400;1,500'],
  ['Hanken Grotesk', 'ital,wght@0,300;0,400;0,500;0,600;0,700;1,400'],
  ['Marcellus', 'wght@400'],
  ['Cinzel', 'wght@400;500'],
  ['Cinzel Decorative', 'wght@400;700'],
  ['Fraunces', 'ital,opsz,wght@0,9..144,300..600;1,9..144,300..500'],
  ['Josefin Sans', 'ital,wght@0,300;0,400;0,500;0,600;1,300;1,400'],
  ['Jost', 'ital,wght@0,300;0,400;0,500;0,600;1,300;1,400'],
  ['Manrope', 'wght@300;400;500;600;700'],
  ['Pinyon Script', 'wght@400'],
  ['Allura', 'wght@400'],
  ['Great Vibes', 'wght@400'],
  ['Parisienne', 'wght@400'],
  ['Italianno', 'wght@400'],
  ['Tangerine', 'wght@400;700'],
  ['Mrs Saint Delafield', 'wght@400'],
  ['Sacramento', 'wght@400'],
];

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';

await fs.mkdir(OUT_DIR, { recursive: true });
await fs.mkdir(path.dirname(CSS_OUT), { recursive: true });

const faces = [];

for (const [family, spec] of FAMILIES) {
  const url = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(family).replace(/%20/g, '+')}:${spec}&display=swap`;
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) {
    console.error(`Failed ${family}: ${res.status}`);
    continue;
  }
  const css = await res.text();
  const blocks = css.split('@font-face').slice(1);
  for (const block of blocks) {
    if (!/unicode-range:\s*U\+0000-00FF/.test(block)) continue;
    const style = /font-style:\s*(\w+)/.exec(block)?.[1] ?? 'normal';
    const weight = /font-weight:\s*([\d\s]+);/.exec(block)?.[1]?.trim() ?? '400';
    const src = /url\((https:[^)]+\.woff2)\)/.exec(block)?.[1];
    if (!src) continue;
    const slug = family.toLowerCase().replace(/[^a-z]+/g, '-');
    const file = `${slug}-${weight.replace(/\s+/g, '-')}-${style}.woff2`;
    const target = path.join(OUT_DIR, file);
    try {
      await fs.access(target);
    } catch {
      const bin = await fetch(src, { headers: { 'User-Agent': UA } });
      if (!bin.ok) {
        console.error(`Failed font file ${file}: ${bin.status}`);
        continue;
      }
      await fs.writeFile(target, Buffer.from(await bin.arrayBuffer()));
    }
    faces.push({ family, style, weight, file });
  }
  console.log(`✓ ${family} (${blocks.length} blocks)`);
}

const css = `/* Generated by scripts/fetch-fonts.mjs — locally served, OFL/Apache licensed Google Fonts */
${faces
  .map(
    (f) => `@font-face {
  font-family: '${f.family}';
  font-style: ${f.style};
  font-weight: ${f.weight};
  font-display: swap;
  src: url('/fonts/${f.file}') format('woff2');
  unicode-range: U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+2000-206F, U+2074, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD;
}`,
  )
  .join('\n\n')}
`;

await fs.writeFile(CSS_OUT, css);
console.log(`\nWrote ${faces.length} @font-face rules to ${path.relative(ROOT, CSS_OUT)}`);
